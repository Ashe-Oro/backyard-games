// Baseline resolution for the shared/cornhole drift check.
//
// The baseline is the released commit a07afaa (tag v1.0.3, Backyard Cornhole 1.0.3), read
// straight from git. Both source-backed platforms are measured there:
//   web           cornhole/index.html, cornhole/controls.mjs   (the site lived at the repo root then)
//   arcade-1.0.3  arcade/cabinet-snapshots/1.0.3/...           (immutable; same paths today)
//   wii           no sources; inherits arcade-1.0.3 (overrides/wii.json "baseline")
// baseline.json is the committed record of those values; the drift test re-derives it from git.
import fs from 'node:fs';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import {currentValues,sha256} from './drift.mjs';

export const SPEC={
 ref:'a07afaa',
 commit:'a07afaa4ada23f365babc45544cc36547446734a',
 tag:'v1.0.3',
 files:{
  web:{game:'cornhole/index.html',controls:'cornhole/controls.mjs'},
  'arcade-1.0.3':{
   game:'arcade/cabinet-snapshots/1.0.3/resources-app/dist/site/cornhole/index.html',
   controls:'arcade/cabinet-snapshots/1.0.3/resources-app/dist/site/cornhole/controls.mjs',
   spin:'arcade/cabinet-snapshots/1.0.3/resources-app/dist/site/cornhole/spin.mjs',
   trackball:'arcade/cabinet-snapshots/1.0.3/resources-app/dist/site/arcade/trackball.mjs',
  },
 },
};

export function loadShared(shared){
 const json=file=>JSON.parse(fs.readFileSync(path.join(shared,file),'utf8'));
 const overrides=Object.fromEntries(fs.readdirSync(path.join(shared,'overrides')).filter(f=>f.endsWith('.json')).sort().map(f=>{const o=json(path.join('overrides',f));return [o.platform,o];}));
 return {common:json('common.json'),overrides,approvals:json('approvals.json'),baseline:fs.existsSync(path.join(shared,'baseline.json'))?json('baseline.json'):null};
}
// Current sources for every platform whose overrides file names source files.
export function loadSources(repo,overrides){
 const out={};
 for(const [platform,data] of Object.entries(overrides)){
  const files=Object.entries(data.files??{});
  if(files.length)out[platform]=Object.fromEntries(files.map(([key,rel])=>[key,fs.readFileSync(path.join(repo,rel),'utf8')]));
 }
 return out;
}
export function commitAvailable(repo,commit){
 try{execFileSync('git',['-C',repo,'cat-file','-e',commit+'^{commit}'],{stdio:'ignore'});return true;}catch{return false;}
}
export function gitShow(repo,commit,rel){
 return execFileSync('git',['-C',repo,'show',`${commit}:${rel}`],{encoding:'utf8',maxBuffer:64*1024*1024,stdio:['ignore','pipe','ignore']});
}
// Sources at the baseline commit, keyed like loadSources().
export function baselineSources(repo,spec=SPEC){
 return Object.fromEntries(Object.entries(spec.files).map(([platform,files])=>[platform,Object.fromEntries(Object.entries(files).map(([key,rel])=>[key,gitShow(repo,spec.commit,rel)]))]));
}
// Build the baseline.json document from sources at the baseline commit.
export function buildBaseline({common,overrides},sources,spec=SPEC){
 return {
  $comment:'Generated by `node shared/cornhole/tools/baseline.mjs --write`. Values every source-backed platform used at the baseline commit, extracted by lib/drift.mjs. Do not hand-edit: the drift test re-derives this file from git. Any current value that differs needs an exact approval in approvals.json.',
  schema:1,
  ref:spec.ref,
  commit:spec.commit,
  tag:spec.tag,
  platforms:Object.fromEntries(Object.entries(spec.files).map(([platform,files])=>[platform,{files:Object.fromEntries(Object.entries(files).map(([key,rel])=>[key,{path:rel,sha256:sha256(sources[platform][key])}]))}])),
  values:currentValues({common,overrides},sources),
 };
}
// Differences between a recorded baseline.json and one re-derived from git (empty = trustworthy).
export function compareBaseline(recorded,derived){
 const errors=[],plain=v=>JSON.stringify(v);
 for(const key of ['ref','commit','tag'])if(recorded[key]!==derived[key])errors.push(`baseline.json ${key} ${plain(recorded[key])} but git baseline is ${plain(derived[key])}`);
 if(plain(recorded.platforms)!==plain(derived.platforms))errors.push('baseline.json file paths/hashes differ from git');
 for(const platform of new Set([...Object.keys(recorded.values??{}),...Object.keys(derived.values)])){
  const r=recorded.values?.[platform]??{},d=derived.values[platform]??{};
  for(const field of new Set([...Object.keys(r),...Object.keys(d)]))if(plain(r[field])!==plain(d[field]))errors.push(`baseline.json ${platform} ${field} is ${plain(r[field])} but ${derived.ref} sources give ${plain(d[field])}; regenerate with node shared/cornhole/tools/baseline.mjs --write`);
 }
 return errors;
}
