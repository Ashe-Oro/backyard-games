#!/usr/bin/env node
// Generates wii/source/core/cornhole_constants.h from shared/cornhole (common.json +
// overrides/arcade-1.0.3.json, the Wii baseline, + overrides/wii.json). The C core never
// restates a shared rules value by hand: it includes this header.
//
//   node wii/tools/gen-constants.mjs           write the header
//   node wii/tools/gen-constants.mjs --check   exit 1 if the committed header is stale
import {readFileSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, '..', '..');
const shared = join(repo, 'shared', 'cornhole');
const out = join(repo, 'wii', 'source', 'core', 'cornhole_constants.h');
const read = (p) => JSON.parse(readFileSync(join(shared, p), 'utf8'));

const common = read('common.json');
const arcade = read('overrides/arcade-1.0.3.json');
const wii = read('overrides/wii.json');
if (wii.baseline !== 'arcade-1.0.3') throw new Error(`wii.json baseline must be arcade-1.0.3, got ${wii.baseline}`);

const values = new Map();
const origin = new Map();
for (const c of common.constants) { values.set(c.name, c.value); origin.set(c.name, 'common.json'); }
for (const o of arcade.overrides) { values.set(o.name, o.value); origin.set(o.name, 'overrides/arcade-1.0.3.json'); }
for (const o of wii.overrides) { values.set(o.name, o.value); origin.set(o.name, 'overrides/wii.json'); }
const rule = (id) => {
  const r = common.rules.find((x) => x.id === id);
  if (!r) throw new Error(`missing rule ${id}`);
  return r.value;
};

const num = (v) => {
  if (typeof v !== 'number' || !Number.isFinite(v)) throw new Error(`not a finite number: ${v}`);
  // Round-trip exact doubles: JS shortest repr parses back to the same IEEE value in C.
  const s = String(v);
  return /[.eE]/.test(s) ? s : `${s}.0`;
};
const need = (name) => {
  if (!values.has(name)) throw new Error(`shared/cornhole has no value for ${name}`);
  return values.get(name);
};

const lines = [];
const def = (cname, value, from) => lines.push(`#define ${cname.padEnd(28)} ${value}${from ? `  /* ${from} */` : ''}`);
const scalar = (name, cname = `BYC_${name}`) => def(cname, num(need(name)), `${origin.get(name)} ${name}`);

for (const name of ['G', 'IN', 'FT', 'W', 'L', 'FRONT_H', 'BACK_H', 'TH', 'BOARD_Z', 'HOLE_FROM_TOP', 'HOLE_R',
  'BAG', 'BAG_H', 'BAG_R', 'STICKY_MU', 'STICKY_MS', 'STICKY_KEEP', 'SLICK_MU', 'SLICK_MS', 'SLICK_KEEP',
  'MU_GROUND', 'BAG_E', 'ELEV', 'V_MIN', 'AIM_MAX', 'REL_Y', 'REL_Z', 'ARC_PUSH_DEG', 'ARC_NORMAL_DEG',
  'ARC_KOBE_DEG', 'LAND_KEEP_KOBE', 'LAND_KEEP_PUSH', 'SWISH_R_FRAC', 'SLIDE_IN_MARGIN', 'PHYSICS_DT',
  'WIND_MPH_TO_ACCEL', 'AIR_SPIN_RATE', 'FLIGHT_CURL', 'SPEED_WINDOW_MS']) scalar(name);

const curl = need('CURL');
def('BYC_CURL_SLICK_ACCEL', num(curl.slick.acceleration), `${origin.get('CURL')} CURL.slick`);
def('BYC_CURL_SLICK_DECAY', num(curl.slick.decay), `${origin.get('CURL')} CURL.slick`);
def('BYC_CURL_STICKY_ACCEL', num(curl.sticky.acceleration), `${origin.get('CURL')} CURL.sticky`);
def('BYC_CURL_STICKY_DECAY', num(curl.sticky.decay), `${origin.get('CURL')} CURL.sticky`);
def('BYC_HUMAN_SPIN', need('HUMAN_SPIN') ? '1' : '0', `${origin.get('HUMAN_SPIN')} HUMAN_SPIN`);
if (need('POWER_INPUT') !== 'swing-speed') throw new Error('POWER_INPUT must stay swing-speed');
def('BYC_POWER_INPUT_SWING_SPEED', '1', `${origin.get('POWER_INPUT')} POWER_INPUT (never distance)`);

lines.push('');
def('BYC_POINTS_IN_HOLE', String(rule('points-in-hole')), 'common.json rule points-in-hole');
def('BYC_POINTS_ON_BOARD', String(rule('points-on-board')), 'common.json rule points-on-board');
def('BYC_TARGET_SCORE', String(rule('target-score')), 'common.json rule target-score');
def('BYC_EXACT_BUST_TO', String(rule('exact-21-bust-to')), 'common.json rule exact-21-bust-to');
def('BYC_BAGS_PER_INNING', String(rule('bags-per-inning')), 'common.json rule bags-per-inning');
for (const id of ['last-scorer-throws-first', 'alternating-throws', 'grounder-is-dead'])
  if (rule(id) !== true) throw new Error(`rule ${id} changed; review rules.c before regenerating`);

lines.push('');
const wind = common.wind;
if (wind.practiceIsCalm !== true || wind.laterRoundsSwitchSides !== true) throw new Error('wind policy changed; review wind code');
def('BYC_WIND_TIER_COUNT', String(wind.tiersByCircuit.length), 'common.json wind.tiersByCircuit');
lines.push(`#define BYC_WIND_TIERS { ${wind.tiersByCircuit.map(([m, s]) => `{${m}, ${s}}`).join(', ')} }  /* [min mph, steps] */`);
def('BYC_WIND_DEFAULT_MIN', String(wind.defaultTier[0]), 'common.json wind.defaultTier');
def('BYC_WIND_DEFAULT_STEPS', String(wind.defaultTier[1]), 'common.json wind.defaultTier');

const sources = ['common.json', 'overrides/arcade-1.0.3.json', 'overrides/wii.json'];
const header = `/* GENERATED by wii/tools/gen-constants.mjs from shared/cornhole/{${sources.join(', ')}}.
 * Do not edit. Change the shared JSON (with a drift approval) and regenerate:
 *   node wii/tools/gen-constants.mjs
 * Wii baseline: arcade 1.0.3. Wii overrides applied: ${wii.overrides.length}. */
#ifndef BYC_CORNHOLE_CONSTANTS_H
#define BYC_CORNHOLE_CONSTANTS_H

${lines.join('\n')}

#endif
`;

if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(out, 'utf8'); } catch {}
  if (current !== header) { console.error('cornhole_constants.h is stale: run node wii/tools/gen-constants.mjs'); process.exit(1); }
  console.log('cornhole_constants.h matches shared/cornhole');
} else {
  writeFileSync(out, header);
  console.log(`wrote ${out}`);
}
