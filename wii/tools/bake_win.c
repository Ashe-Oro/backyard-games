/* Host tool: bakes WIN[team][side][arc] from the C physics core into a C source file (hex floats,
 * exact) that the Wii build links as byc_win. Replaces the ~2M-step startup computation of 1.0.3
 * (SPEC §2.2). The golden test checks the same computation against the pinned JS oracle. */
#include <stdio.h>
#include "physics.h"

int main(int argc, char **argv) {
    if (argc != 2) { fprintf(stderr, "usage: bake-win out.c\n"); return 2; }
    physics_init();
    WinTable t;
    win_compute(&t);
    FILE *f = fopen(argv[1], "w");
    if (!f) { perror(argv[1]); return 1; }
    fprintf(f, "/* GENERATED by wii/tools/bake_win.c from the C physics core. Do not edit. */\n");
    fprintf(f, "#include \"physics.h\"\nconst WinTable byc_win = {{\n");
    for (int a = 0; a < 2; a++) {
        fprintf(f, " {\n");
        for (int s = 0; s < 2; s++) {
            fprintf(f, "  {");
            for (int r = 0; r < 3; r++) {
                WinWindow w = t.w[a][s][r];
                fprintf(f, "{%a, %a, %a, %a, %a}%s", w.lo, w.hi, w.olo, w.ohi, w.mid, r < 2 ? ", " : "");
            }
            fprintf(f, "}%s\n", s < 1 ? "," : "");
        }
        fprintf(f, " }%s\n", a < 1 ? "," : "");
    }
    fprintf(f, "}};\n");
    return fclose(f) == 0 ? 0 : 1;
}
